_normalize_domain() {
  local d="${1:-}"
  d="${d#"${d%%[![:space:]]*}"}"
  d="${d%"${d##*[![:space:]]}"}"
  [[ -z "$d" ]] && return 0
  d="$(printf '%s' "$d" | sed -E 's|^[Hh][Tt][Tt][Pp][Ss]?://||')"
  d="${d%%/*}"
  d="${d%%:*}"
  d="${d%.}"
  printf '%s' "$d"
}

