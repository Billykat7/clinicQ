# Append KEY=value with value JSON-encoded (safe for $, ", newlines in secrets).
_append_json_env_line() {
  local key="$1"
  local val="${2:-}"
  if [ -z "$val" ]; then
    return 0
  fi
  if ! command -v python3 >/dev/null 2>&1; then
    echo "::error::python3 is required to append ${key} (JSON-quoted .env line)." >&2
    exit 1
  fi
  printf '%s' "$val" | python3 -c 'import sys, json; k = sys.argv[1]; v = sys.stdin.read(); print(f"{k}={json.dumps(v)}")' "$key" >>"$OUT"
}

